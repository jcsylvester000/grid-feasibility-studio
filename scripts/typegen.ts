/**
 * Generates lib/contract/types.gen.ts from the GRID schema set (BRD 8.1 rule 4: no hand-written
 * copies). Remote $refs (https://schemas.grid.ph/...) resolve to the local schema files.
 * Usage: npm run typegen   ·   CI: npm run typegen -- --check (fails if the file is stale)
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { compile } from "json-schema-to-typescript";

const dir = path.resolve("lib/contract/schemas");
const out = path.resolve("lib/contract/types.gen.ts");
const BASE = "https://schemas.grid.ph/feasibility-studio/v1/";

const targets: [string, string][] = [
  ["envelope.schema.json", "ResultEnvelopeSchema"],
  ["run_request.schema.json", "RunRequestSchema"],
  ["quick_report.schema.json", "QuickReport"],
  ["executive_summary.schema.json", "ExecutiveSummary"],
  ["feasibility_report.schema.json", "FeasibilityReport"],
  ["teaser_intake.schema.json", "TeaserIntake"],
];

const localResolver = {
  order: 1,
  canRead: (file: { url: string }) => file.url.startsWith(BASE) || file.url.endsWith(".schema.json"),
  read: (file: { url: string }) => {
    const name = file.url.split("/").pop()!.split("#")[0]!;
    return readFileSync(path.join(dir, name), "utf8");
  },
};

async function main() {
  const parts: string[] = [
    "/* eslint-disable */",
    "// GENERATED by scripts/typegen.ts from lib/contract/schemas. Do not edit by hand.",
    "",
  ];
  for (const [file, name] of targets) {
    const schema = JSON.parse(readFileSync(path.join(dir, file), "utf8"));
    schema.title = name;
    const ts = await compile(schema, name, {
      bannerComment: "",
      cwd: dir,
      additionalProperties: false,
      declareExternallyReferenced: true,
      strictIndexSignatures: false,
      unreachableDefinitions: false,
      $refOptions: { resolve: { grid: localResolver } } as never,
    });
    parts.push(`// ---- ${file} ----`, `export namespace ${name}Types {`, ts.replace(/^/gm, "  "), "}", "");
  }
  const text = parts.join("\n");
  if (process.argv.includes("--check")) {
    const current = existsSync(out) ? readFileSync(out, "utf8") : "";
    if (current !== text) {
      console.error("types.gen.ts is out of date. Run npm run typegen.");
      process.exit(1);
    }
    console.log("types.gen.ts is current.");
    return;
  }
  writeFileSync(out, text);
  console.log(`Wrote ${path.relative(process.cwd(), out)} (${text.length} chars).`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
